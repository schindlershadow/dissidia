#!/usr/bin/env python3
"""Generate runtime/src/psp_smaa_data.cpp from the SMAA reference sources (https://github.com/iryoku/smaa, MIT licence).

Usage: gen_smaa.py <dir with SMAA.hlsl AreaTex.h SearchTex.h LICENSE.txt> [output.cpp]

The shader library is embedded with comments stripped (it is compiled with SMAA_GLSL_3 by psp_post.cpp); the two lookup textures
are embedded as byte arrays (area: 160x560 RG8, search: 64x16 R8).
"""
import re, sys, os

def strip_comments(t):
    t = re.sub(r'/\*.*?\*/', '', t, flags=re.S)
    t = re.sub(r'//[^\n]*', '', t)
    out = []
    for l in t.split('\n'):
        l = l.rstrip()
        if l.strip():
            out.append(l)
    return '\n'.join(out) + '\n'

def bytes_of(path, name):
    t = open(path, encoding='latin-1').read()
    m = re.search(name + r'\[\]\s*=\s*\{(.*?)\};', t, re.S)
    return bytes(int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', m.group(1)))

def main():
    src = sys.argv[1]
    dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), '..', 'runtime', 'src', 'psp_smaa_data.cpp')
    lic = open(os.path.join(src, 'LICENSE.txt'), encoding='latin-1').read().replace('\r', '')
    hlsl = strip_comments(open(os.path.join(src, 'SMAA.hlsl'), encoding='latin-1').read().replace('\r', ''))
    area = bytes_of(os.path.join(src, 'AreaTex.h'), 'areaTexBytes')
    search = bytes_of(os.path.join(src, 'SearchTex.h'), 'searchTexBytes')
    assert len(area) == 160 * 560 * 2 and len(search) == 64 * 16, (len(area), len(search))
    chunks, cur = [], ''
    for l in hlsl.split('\n'):
        if len(cur) + len(l) > 9000:
            chunks.append(cur); cur = ''
        cur += l + '\n'
    chunks.append(cur)
    o = ['// GENERATED by tools/gen_smaa.py from the SMAA reference implementation (SMAA.hlsl, AreaTex.h, SearchTex.h). Do not edit.',
         '//', '// SMAA licence:']
    o += ['// ' + l for l in lic.strip().split('\n')]
    o += ['', '#include "psp_smaa_data.h"', '', 'const char* const psp_smaa_lib[] = {']
    for c in chunks:
        assert ')SMAA"' not in c
        o.append('R"SMAA(' + c + ')SMAA",')
    o += ['nullptr};', '']
    def arr(name, b):
        o.append('const unsigned char %s[%d] = {' % (name, len(b)))
        for i in range(0, len(b), 24):
            o.append(','.join(str(x) for x in b[i:i + 24]) + ',')
        o.append('};')
    arr('psp_smaa_area', area); arr('psp_smaa_search', search)
    open(dst, 'w').write('\n'.join(o) + '\n')
    print('wrote', dst, len(hlsl), 'chars of shader,', len(chunks), 'chunks')

main()
