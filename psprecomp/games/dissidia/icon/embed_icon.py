#!/usr/bin/env python3
"""Regenerate the game's icon files from android/icon/icon_512.png (the artwork is drawn by android/icon/make_icon.py):
games/dissidia/icon/installer.ico + runtime/include/psp_app_icon_installer.h (the setup wizard's own icon, android/icon/make_installer_icon.py), icon.png (256 px, Linux menu entry), icon.ico (Windows shortcut), runtime/include/psp_app_icon_dissidia.h (64x64 window icon).
  python3 embed_icon.py      (needs Pillow; run from anywhere)
"""
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
src = Image.open(os.path.join(REPO, "android", "icon", "icon_512.png")).convert("RGBA")
src.resize((256, 256), Image.LANCZOS).save(os.path.join(HERE, "icon.png"), optimize=True)
src.save(os.path.join(HERE, "icon.ico"), sizes=[(16, 16), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
raw = src.resize((64, 64), Image.LANCZOS).tobytes()
body = "\n".join("    " + ",".join("0x%02x" % b for b in raw[i:i + 24]) + "," for i in range(0, len(raw), 24))
with open(os.path.join(REPO, "runtime", "include", "psp_app_icon_dissidia.h"), "w") as f:
    f.write("// Generated by games/dissidia/icon/embed_icon.py from icon.png: 64x64 RGBA window icon of the game. Do not edit.\n"
            "#pragma once\nstatic const int k_app_icon_w = 64, k_app_icon_h = 64;\n"
            "static const unsigned char k_app_icon_rgba[64 * 64 * 4] = {\n" + body + "\n};\n")

# the wizard's own icon (android/icon/make_installer_icon.py draws installer_512.png): installer.ico and a 64x64 window icon
inst = Image.open(os.path.join(REPO, "android", "icon", "installer_512.png")).convert("RGBA")
inst.save(os.path.join(HERE, "installer.ico"), sizes=[(16, 16), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
raw = inst.resize((64, 64), Image.LANCZOS).tobytes()
body = "\n".join("    " + ",".join("0x%02x" % b for b in raw[i:i + 24]) + "," for i in range(0, len(raw), 24))
with open(os.path.join(REPO, "runtime", "include", "psp_app_icon_installer.h"), "w") as f:
    f.write("// Generated by games/dissidia/icon/embed_icon.py from android/icon/installer_512.png: 64x64 RGBA window icon of the setup wizard. Do not edit.\n"
            "#pragma once\nstatic const int k_app_icon_w = 64, k_app_icon_h = 64;\n"
            "static const unsigned char k_app_icon_rgba[64 * 64 * 4] = {\n" + body + "\n};\n")
print("icon files written")
