int main() {
    // release list
    {
        const char* js = R"([{"tag_name":"v1","name":"Turnip v26 R8","published_at":"2026-01-08T01:03:08Z","assets":[
            {"name":"Turnip_v26_R8.zip","size":3478359,"browser_download_url":"https://github.com/x/y/releases/download/v1/Turnip_v26_R8.zip"},
            {"name":"notes.txt","size":10,"browser_download_url":"https://github.com/x/y/releases/download/v1/notes.txt"},
            {"name":"huge.zip","size":999999999,"browser_download_url":"https://github.com/x/y/releases/download/v1/huge.zip"},
            {"name":"http.zip","size":10,"browser_download_url":"http://insecure/http.zip"}]},
            {"tag_name":"v0","name":"","published_at":"2025-12-26T01:13:15Z","assets":[
            {"name":"../a b.zip","size":5,"browser_download_url":"https://github.com/x/y/a.zip"}]}])";
        std::vector<Remote> v;
        std::string err;
        CHECK(parse_releases(js, &v, &err));
        CHECK(v.size() == 2);
        if (v.size() == 2) {
            CHECK(v[0].id == "Turnip_v26_R8" && v[0].size == 3478359 && v[0].published == "2026-01-08");
            CHECK(v[1].id == "_a_b" || v[1].id == "a_b" || v[1].id.find('/') == std::string::npos);
            CHECK(v[1].id.find("..") == std::string::npos);
        }
        std::vector<Remote> none;
        CHECK(!parse_releases("{\"message\":\"API rate limit exceeded\"}", &none, &err) && err == "API rate limit exceeded");
        CHECK(!parse_releases("[{", &none, &err));
    }
    // curate: variants and newer-generation packages dropped, Turnip first, Qualcomm last, readable names
    {
        auto mk = [](const char* id, const char* date) { Remote r; r.id = id; r.name = id; r.published = date; r.size = 1; return r; };
        std::vector<Remote> v{mk("Qualcomm_840_adpkg", "2026-01-14"), mk("turnip_a8xx", "2026-01-08"), mk("Turnip_v26.0.0_R8", "2026-01-08"),
                              mk("Turnip_v26.0.0_R8_Gmem", "2026-01-08"), mk("Turnip_v26.0.0_R8_Sysmem", "2026-01-08"), mk("Turnip_v26.0.0_R7", "2025-12-26"),
                              mk("Turnip_v26.0.0_R7", "2025-12-26"), mk("Other_driver", "2026-02-01")};
        std::vector<Remote> a = v;
        curate(&a, 7);
        CHECK(a.size() == 4);
        if (a.size() == 4) CHECK(a[0].id == "Turnip_v26.0.0_R8" && a[1].id == "Turnip_v26.0.0_R7" && a[2].id == "Other_driver" && a[3].id == "Qualcomm_840_adpkg");
        if (!a.empty()) CHECK(a[0].name == "Turnip v26.0.0 R8");
        std::vector<Remote> b = v;
        curate(&b, 8);
        CHECK(b.size() == 5);   // a8xx kept on an Adreno 8xx
        std::vector<Remote> c = v;
        curate(&c, 0);
        CHECK(c.size() == 5);   // unknown generation: keep all
    }
    // meta.json
    {
        Installed in;
        CHECK(parse_meta(R"({"name":"N","driverVersion":"V","minApi":27,"libraryName":"vulkan.x.so"})", &in) && in.library == "vulkan.x.so" && in.min_api == 27);
        CHECK(!parse_meta(R"({"name":"N","libraryName":"../x.so"})", &in));
        CHECK(!parse_meta(R"({"name":"N"})", &in));
        CHECK(parse_meta(R"({"name":"\u00e9\ud83d\ude00","libraryName":"a.so"})", &in) && in.name.size() == 6);
    }
    CHECK(sanitize_id("../../etc/passwd") == "_.._etc_passwd" || sanitize_id("../../etc/passwd").find('/') == std::string::npos);
    CHECK(sanitize_id(".hidden") == "hidden");
    // unpack
    {
        char tmpl[] = "/tmp/gpudrvXXXXXX";
        const char* base = mkdtemp(tmpl);
        CHECK(base != nullptr);
        std::string dir = std::string(base) + "/pkg";
        std::vector<uint8_t> z(k_zip, k_zip + sizeof k_zip);
        Installed in;
        std::string err;
        CHECK(unpack_package(z, dir, &in, &err));
        CHECK(in.name == "Test Turnip" && in.library == "vulkan.ad07xx.so");
        FILE* f = std::fopen((dir + "/vulkan.ad07xx.so").c_str(), "rb");
        CHECK(f != nullptr);
        if (f) { char b[8]; CHECK(std::fread(b, 1, 8, f) == 8 && !std::memcmp(b, "\x7f" "ELFabcd", 8)); std::fclose(f); }
        CHECK(access((std::string(base) + "/evil.so").c_str(), F_OK) != 0 && access((dir + "/evil.so").c_str(), F_OK) != 0);   // nothing but meta + library
        // installed() sees it under PSPRECOMP_GPU_DRIVER_DIR
        setenv("PSPRECOMP_GPU_DRIVER_DIR", base, 1);
        auto v = installed();
        CHECK(v.size() == 1 && v[0].id == "pkg" && v[0].name == "Test Turnip");
        CHECK(psp_gpu::remove("pkg"));
        CHECK(installed().empty());
        CHECK(!psp_gpu::remove("../x"));
        // damaged input
        std::vector<uint8_t> bad = z;
        bad.resize(bad.size() / 2);
        CHECK(!unpack_package(bad, dir + "2", &in, &err));
        CHECK(!unpack_package(std::vector<uint8_t>(100, 0), dir + "3", &in, &err));
        // crash marker
        CHECK(!crashed("pkg"));
        std::string cmd = std::string("rm -rf ") + base;
        if (std::system(cmd.c_str())) {}
    }
    std::printf(g_fail ? "FAILED (%d)\n" : "OK\n", g_fail);
    return g_fail ? 1 : 0;
}
